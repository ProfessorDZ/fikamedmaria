/* =====================================================================
   Fika med Maria — languages.
   Ukrainian pages live at the site root; Swedish, English and Polish copies
   live in /sv/, /en/ and /pl/ (generated by i18n/build.py). The page's
   <html lang> says which one this is. Text that JavaScript draws is passed
   through T(): on a non-Ukrainian page it is looked up in window.FMM_I18N
   (assets/i18n/<lang>.js, loaded just before this file); a missing string
   simply stays Ukrainian. Loaded on every page before data.js.
   ===================================================================== */
(function () {
  "use strict";

  var LANGS = [
    { code: "uk", name: "Українська", short: "UA" },
    { code: "sv", name: "Svenska", short: "SV" },
    { code: "en", name: "English", short: "EN" },
    { code: "pl", name: "Polski", short: "PL" }
  ];

  function known(code) {
    for (var i = 0; i < LANGS.length; i++) { if (LANGS[i].code === code) return LANGS[i]; }
    return null;
  }

  var lang = String(document.documentElement.getAttribute("lang") || "uk").toLowerCase().slice(0, 2);
  if (!known(lang)) lang = "uk";

  var pack = window.FMM_I18N;
  var strings = pack && pack.lang === lang && pack.strings ? pack.strings : {};

  /* The site root, taken from this file's own address (…/assets/i18n.js),
     so links work the same at the root, in /blog/ and in /sv/blog/. */
  var root;
  try {
    var me = document.currentScript && document.currentScript.src;
    root = me ? new URL("..", me).href : new URL("./", window.location.href).href;
  } catch (_) {
    root = "/";
  }
  var langRoot = root + (lang === "uk" ? "" : lang + "/");

  function T(text, vars) {
    var s = String(text == null ? "" : text);
    var out = Object.prototype.hasOwnProperty.call(strings, s) && strings[s] ? strings[s] : s;
    if (vars) {
      out = out.replace(/\{([a-zA-Z_][a-zA-Z0-9_]*)\}/g, function (m, k) {
        return Object.prototype.hasOwnProperty.call(vars, k) && vars[k] != null ? String(vars[k]) : m;
      });
    }
    return out;
  }

  function isAbsolute(u) {
    return /^(?:[a-zA-Z][a-zA-Z0-9+.-]*:|\/\/|#)/.test(u);
  }

  /* A page of this site in the current language: url("kursy.html"). */
  function url(path) {
    path = String(path == null ? "" : path);
    if (path === "" || isAbsolute(path)) return path;
    if (path.charAt(0) === "/") return root + path.slice(1);
    return langRoot + path;
  }

  /* A shared file (images, scripts): asset("assets/maria.jpg"). */
  function asset(path) {
    path = String(path == null ? "" : path);
    if (path === "" || isAbsolute(path)) return path;
    return root + path.replace(/^\/+/, "");
  }

  /* Blog covers have their headline drawn into the picture, so each language
     has its own copy in assets/blog/<lang>/ (same file name). */
  function localizedAsset(path) {
    path = String(path == null ? "" : path);
    if (lang !== "uk" && /^assets\/blog\/[^/]+$/.test(path)) {
      return asset(path.replace(/^assets\/blog\//, "assets/blog/" + lang + "/"));
    }
    return asset(path);
  }

  /* <link rel="alternate" hreflang> for a page whose content depends on its
     ?id= (a lesson or a course): written once the id is known. */
  function addAlternates() {
    var head = document.head;
    if (!head || head.querySelector('link[rel="alternate"][hreflang]')) return;
    var all = LANGS.map(function (l) { return { code: l.code, href: switchUrl(l.code) }; });
    all.push({ code: "x-default", href: switchUrl("uk") });
    all.forEach(function (a) {
      var link = document.createElement("link");
      link.rel = "alternate";
      link.hreflang = a.code;
      link.href = a.href.split("#")[0];
      head.appendChild(link);
    });
  }

  /* This page's address below the language folder, with ?query and #hash. */
  function currentPath() {
    var tail = window.location.search + window.location.hash;
    /* href, not origin + pathname: Firefox reports origin "null" for file:// pages */
    var here = window.location.href.split(/[?#]/)[0];
    /* "/sv" without the closing slash is the Swedish home page too. */
    if (here + "/" === langRoot) return tail;
    if (here.indexOf(langRoot) === 0) return here.slice(langRoot.length) + tail;
    if (here.indexOf(root) === 0) return here.slice(root.length) + tail;
    return window.location.pathname.split("/").pop() + tail;
  }

  function switchUrl(code) {
    return root + (code === "uk" ? "" : code + "/") + currentPath();
  }

  function remember(code) {
    try { window.localStorage.setItem("fmm_lang", code); } catch (_) {}
  }

  /* The header's language menu. A <details> opens and closes without any
     script; the script closes it on an outside click, when keyboard focus
     leaves it, and on Escape pressed inside it. */
  function switcherHtml() {
    var cur = known(lang);
    var items = LANGS.map(function (l) {
      var on = l.code === lang;
      return '<li><a href="' + switchUrl(l.code) + '" hreflang="' + l.code + '" lang="' + l.code + '"' +
        ' data-lang-pick="' + l.code + '"' + (on ? ' aria-current="true" class="is-current"' : "") + ">" +
        '<span class="lang-short">' + l.short + "</span>" + l.name + "</a></li>";
    }).join("");
    return '<details class="lang-switch" data-lang-switch>' +
      '<summary aria-label="' + T("Мова сайту") + ": " + cur.name + '">' +
        '<svg viewBox="0 0 24 24" width="18" height="18" fill="none" stroke="currentColor" stroke-width="1.8" aria-hidden="true">' +
          '<circle cx="12" cy="12" r="9"/><path d="M3 12h18M12 3c2.5 2.6 3.8 5.6 3.8 9s-1.3 6.4-3.8 9c-2.5-2.6-3.8-5.6-3.8-9S9.5 5.6 12 3z"/>' +
        "</svg>" +
        '<span class="lang-current">' + cur.short + "</span>" +
      "</summary>" +
      '<ul class="lang-menu">' + items + "</ul>" +
    "</details>";
  }

  function wireSwitcher() {
    var box = document.querySelector("[data-lang-switch]");
    if (!box) return;
    box.addEventListener("click", function (e) {
      var a = e.target.closest ? e.target.closest("[data-lang-pick]") : null;
      if (a) remember(a.getAttribute("data-lang-pick"));
    });
    document.addEventListener("click", function (e) {
      if (box.open && !box.contains(e.target)) box.open = false;
    });
    box.addEventListener("focusout", function (e) {
      if (box.open && e.relatedTarget && !box.contains(e.relatedTarget)) box.open = false;
    });
    box.addEventListener("keydown", function (e) {
      if (e.key === "Escape" && box.open) {
        box.open = false;
        var s = box.querySelector("summary");
        if (s) s.focus();
      }
    });
  }

  window.T = T;
  window.FMMI18N = {
    lang: lang,
    langs: LANGS,
    root: root,
    langRoot: langRoot,
    T: T,
    url: url,
    asset: asset,
    localizedAsset: localizedAsset,
    addAlternates: addAlternates,
    switchUrl: switchUrl,
    switcherHtml: switcherHtml,
    wireSwitcher: wireSwitcher
  };
})();
